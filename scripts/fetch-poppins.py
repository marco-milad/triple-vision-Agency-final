"""Bring Poppins into the repo instead of fetching it from Google on every visit.

Self-hosting removes a third-party request from the critical path, removes the
flash of fallback type while that request is in flight, and keeps the site
looking right where fonts.googleapis.com is blocked.

Only the weights the code actually uses are fetched, and only the Latin subsets:
the site is English, so the Devanagari files Google also serves are 40% of the
bytes for nothing.

Poppins is licensed under the SIL Open Font License, which permits this.

Run from the project root:  python scripts/fetch-poppins.py
"""
import io
import os
import re
import subprocess

UA = ("Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
      "(KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36")

# the weights that appear in the components: normal, medium, semibold, bold, black
WEIGHTS = [400, 500, 600, 700, 900]
SUBSETS = ["latin", "latin-ext"]

OUT_DIR = "public/fonts"
CSS_OUT = "src/styles/poppins.css"
SOURCE = ("https://fonts.googleapis.com/css2?family=Poppins:wght@"
          + ";".join(str(w) for w in WEIGHTS) + "&display=swap")


def google_css():
    result = subprocess.run(["curl", "-s", "-A", UA, SOURCE], capture_output=True, check=True)
    return result.stdout.decode("utf-8")


def blocks(css):
    """Each @font-face, tagged with the subset comment that precedes it."""
    out = []
    for match in re.finditer(r"/\* ([a-z-]+) \*/\s*(@font-face \{[^}]*\})", css):
        subset, body = match.group(1), match.group(2)
        weight = re.search(r"font-weight: (\d+)", body)
        url = re.search(r"url\((https://[^)]+\.woff2)\)", body)
        unicode_range = re.search(r"unicode-range: ([^;]+);", body)
        if not (weight and url and unicode_range):
            continue
        out.append({
            "subset": subset,
            "weight": int(weight.group(1)),
            "url": url.group(1),
            "range": unicode_range.group(1).strip(),
        })
    return out


def run():
    os.makedirs(OUT_DIR, exist_ok=True)
    os.makedirs(os.path.dirname(CSS_OUT), exist_ok=True)

    wanted = [b for b in blocks(google_css())
              if b["subset"] in SUBSETS and b["weight"] in WEIGHTS]

    rules, total = [], 0
    for block in sorted(wanted, key=lambda b: (b["weight"], b["subset"])):
        name = "poppins-%s-%d.woff2" % (block["subset"], block["weight"])
        path = os.path.join(OUT_DIR, name)
        if not os.path.exists(path):
            subprocess.run(["curl", "-s", "-A", UA, block["url"], "-o", path], check=True)
        size = os.path.getsize(path)
        total += size
        print("  %-28s %5.0f KB" % (name, size / 1024))
        rules.append(
            "@font-face {\n"
            "  font-family: 'Poppins';\n"
            "  font-style: normal;\n"
            "  font-weight: %d;\n"
            "  font-display: swap;\n"
            "  src: url('/fonts/%s') format('woff2');\n"
            "  unicode-range: %s;\n"
            "}" % (block["weight"], name, block["range"]))

    header = (
        "/*\n"
        " * Poppins, served from this repo rather than from Google.\n"
        " *\n"
        " * Generated by scripts/fetch-poppins.py - edit that, not this.\n"
        " *\n"
        " * Only the weights the components use are here (400, 500, 600, 700, 900)\n"
        " * and only the Latin subsets. Adding a weight to the components without\n"
        " * adding it here leaves the browser to fake it, which looks wrong.\n"
        " *\n"
        " * Poppins is licensed under the SIL Open Font License; see\n"
        " * public/fonts/OFL.txt.\n"
        " */\n\n")

    io.open(CSS_OUT, "w", encoding="utf-8", newline="\n").write(header + "\n\n".join(rules) + "\n")
    print("%d files, %.0f KB total -> %s" % (len(wanted), total / 1024, CSS_OUT))


if __name__ == "__main__":
    run()
