"""Emit the traced logo as two movable parts, plus the transform between its two
layouts.

The intro and the header want different arrangements of the same mark. The logo
file sets "Agency" small and tucked under the right end of VISION, which is
right in a header but reads as a label hanging off the mark when it is alone in
the middle of a screen; there it wants to be a lockup, centred under the words.

So both parts stay in the logo's own coordinates and the second line carries a
transform that puts it in the lockup position. Animating that transform away
returns the mark to exactly the artwork the header shows, which is what lets the
intro dock into the header instead of simply disappearing.

Run from the project root, after scripts/trace-logo.py:
    python scripts/build-wordmark.py
"""
import io
import json
import re

PATHS = "scripts/logo-paths.json"
OUT = "src/components/logoPaths.ts"

BAND_SPLIT = 123          # below this y, a contour belongs to "Agency"
AGENCY_SCALE = 1.45       # brings its cap height to about half the main line's
LINE_GAP = 26.0           # from the baseline of line one to the cap of line two


def contours(d):
    out = []
    for sub in d.split("M")[1:]:
        pts = re.findall(r"(-?\d+\.?\d*),(-?\d+\.?\d*)", sub)
        if len(pts) >= 3:
            out.append([(float(x), float(y)) for x, y in pts])
    return out


def box(contour):
    xs = [x for x, _ in contour]
    ys = [y for _, y in contour]
    return min(xs), min(ys), max(xs), max(ys)


def bounds(cs):
    return (min(box(c)[0] for c in cs), min(box(c)[1] for c in cs),
            max(box(c)[2] for c in cs), max(box(c)[3] for c in cs))


def glyphs(cs):
    """
    Group contours into glyphs by walking left to right and opening a new one
    only where there is clear air between shapes.

    Merging into whichever group happens to overlap does not work: each merge
    widens that group's bounds until it swallows the rest of the word. A counter
    sits strictly inside its letter, so it never opens a glyph of its own.
    """
    out = []
    for c in sorted(cs, key=lambda c: box(c)[0]):
        b = box(c)
        if out and b[0] <= out[-1]["box"][2] + 0.5:
            g = out[-1]
            g["contours"].append(c)
            gb = g["box"]
            g["box"] = (gb[0], min(gb[1], b[1]), max(gb[2], b[2]), max(gb[3], b[3]))
        else:
            out.append({"contours": [c], "box": b})
    return out


def emit(cs):
    return "".join("M" + " L".join("%g,%g" % (round(x, 1), round(y, 1)) for x, y in c) + "Z"
                   for c in cs)


def run():
    data = json.load(open(PATHS))
    white = contours(data["white"])
    orange = contours(data["orange"])

    main = sorted([c for c in white if box(c)[1] < BAND_SPLIT], key=lambda c: box(c)[0])
    agency = sorted([c for c in white if box(c)[1] >= BAND_SPLIT], key=lambda c: box(c)[0])
    print("main line: %d contours   agency: %d contours" % (len(main), len(agency)))
    print("glyphs: %d in the main line, %d in Agency"
          % (len(glyphs(main)), len(glyphs(agency))))

    mx0, my0, mx1, my1 = bounds(main)
    ax0, ay0, ax1, ay1 = bounds(agency)
    print("main   x %.0f..%.0f  y %.0f..%.0f" % (mx0, mx1, my0, my1))
    print("agency x %.0f..%.0f  y %.0f..%.0f" % (ax0, ax1, ay0, ay1))

    # Centre the lockup on the words, not on the words plus the three-bar mark
    # out to their left: including it drags the second line visibly off centre.
    words = [c for c in main if box(c)[0] > mx0 + 30]
    wx0, _, wx1, _ = bounds(words)
    words_mid = (wx0 + wx1) / 2

    scaled_w = (ax1 - ax0) * AGENCY_SCALE
    target_x = words_mid - scaled_w / 2
    target_y = my1 + LINE_GAP

    # SVG scales about the origin, so the translate has to undo wherever that
    # scaling moved the glyphs' own top-left corner.
    s = AGENCY_SCALE
    tx = target_x - ax0 * s
    ty = target_y - ay0 * s
    lockup = "translate(%.2f %.2f) scale(%.3f)" % (tx, ty, s)
    print("lockup transform: %s" % lockup)

    low = target_y + (ay1 - ay0) * s
    print("lockup reaches y %.0f (the logo's own box is 178 tall)" % low)

    # the union of both parts, in the logo's own coordinates
    ink = (round(min(mx0, ax0)), round(min(my0, ay0)),
           round(max(mx1, ax1)), round(max(my1, ay1)))
    print("ink box: x %d..%d  y %d..%d" % (ink[0], ink[2], ink[1], ink[3]))

    ts = '''/**
 * The wordmark, traced from the logo file, as two parts that can be arranged
 * two ways.
 *
 * Generated by scripts/build-wordmark.py. Both parts are in the logo's own
 * coordinates, so with no transform applied they are exactly the artwork the
 * header shows. `AGENCY_LOCKUP` moves the second line to where the intro wants
 * it - scaled up and centred under the words - and animating that transform
 * away reassembles the header's layout.
 *
 * Contours are in reading order, so a stroke sweeping the path travels left to
 * right. Every path fills with fill-rule="evenodd", which turns the inner
 * contours of R, P, O, A, g and e into counters.
 */

/** The logo's own box. The lockup overflows below it, so the svg must not clip. */
export const LOGO_VIEWBOX = '0 0 640 178';

/**
 * Where the ink actually sits inside that box: [x0, y0, x1, y1].
 *
 * The box has margin around the artwork, and the header's copy of the same file
 * has the same margin. Docking one onto the other is measured on the ink, so
 * nothing depends on the two boxes being laid out identically.
 */
export const LOGO_INK = [%d, %d, %d, %d] as const;

/** How far below that box the second line reaches while it is in lockup. */
export const LOCKUP_OVERFLOW = %d;

/**
 * TRIPLE VISION and the three bars, one entry per glyph so the intro can write
 * them one at a time. In reading order.
 */
export const MAIN_GLYPHS = [
%s
];

/**
 * "Agency", in its header position, also per glyph — though its letters touch
 * in the artwork, so they come out as three groups rather than six letters.
 */
export const AGENCY_GLYPHS = [
%s
];

/** Puts "Agency" where the intro wants it; removing it docks the header layout. */
export const AGENCY_LOCKUP = '%s';

/** The play mark inside the O. */
export const LOGO_ORANGE = '%s';
''' % (ink[0], ink[1], ink[2], ink[3],
       round(low),
       "\n".join("  '%s'," % emit(g["contours"]) for g in glyphs(main)),
       "\n".join("  '%s'," % emit(g["contours"]) for g in glyphs(agency)),
       lockup, emit(orange))

    io.open(OUT, "w", encoding="utf-8", newline="\n").write(ts)
    print("-> %s  %.1f KB" % (OUT, len(ts) / 1024))


if __name__ == "__main__":
    run()
